-- Function to initialize default permissions for a user based on unvan
CREATE OR REPLACE FUNCTION public.initialize_user_permissions(target_user_id BIGINT, user_unvan TEXT)
RETURNS VOID AS $$
BEGIN
    -- Common permissions for everyone
    INSERT INTO public.user_permissions (user_id, permission_id)
    VALUES (target_user_id, 'inventory:view'), (target_user_id, 'tasks:view'), (target_user_id, 'vehicles:view'), (target_user_id, 'map:view'), (target_user_id, 'attendance:view')
    ON CONFLICT DO NOTHING;

    -- Role specific permissions
    IF user_unvan IN ('mudur', 'sef', 'bolge_sorumlusu') THEN
        INSERT INTO public.user_permissions (user_id, permission_id)
        SELECT target_user_id, id FROM public.permissions
        ON CONFLICT DO NOTHING;
    ELSIF user_unvan = 'ekipbasi' THEN
        INSERT INTO public.user_permissions (user_id, permission_id)
        VALUES 
            (target_user_id, 'inventory:output'),
            (target_user_id, 'tasks:create'),
            (target_user_id, 'tasks:manage'),
            (target_user_id, 'users:view'),
            (target_user_id, 'attendance:manage')
        ON CONFLICT DO NOTHING;
    END IF;
END;
$$ LANGUAGE plpgsql;

-- Trigger to auto-initialize permissions when a user is created
CREATE OR REPLACE FUNCTION public.trigger_initialize_user_permissions()
RETURNS TRIGGER AS $$
BEGIN
    PERFORM public.initialize_user_permissions(NEW.id, NEW.unvan);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_init_user_perms ON public.users;
CREATE TRIGGER tr_init_user_perms
AFTER INSERT ON public.users
FOR EACH ROW EXECUTE FUNCTION public.trigger_initialize_user_permissions();

