-- Ensure Users Table exists
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad_soyad TEXT NOT NULL,
    unvan TEXT,
    ilce TEXT,
    email TEXT UNIQUE,
    auth_id UUID UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    telefon TEXT,
    kan_grubu TEXT,
    durum TEXT DEFAULT 'aktif'
);

-- Permissions Table
CREATE TABLE IF NOT EXISTS public.permissions (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT
);

-- User Permissions Junction Table
CREATE TABLE IF NOT EXISTS public.user_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    permission_id TEXT REFERENCES public.permissions(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, permission_id)
);

-- RLS
ALTER TABLE public.permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if they exist to avoid "already exists" errors
DROP POLICY IF EXISTS "Permissions Public Access" ON public.permissions;
DROP POLICY IF EXISTS "User Permissions Public Access" ON public.user_permissions;
DROP POLICY IF EXISTS "Users Public Access" ON public.users;

-- Create policies
CREATE POLICY "Permissions Public Access" ON public.permissions FOR SELECT USING (true);
CREATE POLICY "User Permissions Public Access" ON public.user_permissions FOR ALL USING (true);
CREATE POLICY "Users Public Access" ON public.users FOR ALL USING (true);

